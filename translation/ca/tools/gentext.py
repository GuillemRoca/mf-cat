#!/usr/bin/env python3
"""Generates the Catalan text and its pointer tables for LANG_CA=1.

  gentext.py asm OUTPUT.s [--selftest]
      Every string of the English slot, as assembly for the object that linker.ld places after
      everything else in the ROM: the Catalan text of translation/ca/text/<category>.txt, or the
      vanilla English where no translation exists yet. Each string is `sCaText_<ID>`.
  gentext.py tables OUTPUT.h [--selftest]
      The C header src/new_file_intro.c includes: the three pointer tables that hold English
      pointers, with every other pointer as in the ROM and the English ones replaced by
      `sCaText_<ID>`. The tables keep their place and size, so nothing in the ROM moves.

  --selftest ignores the translation: the appended strings are the vanilla English ones
  (CA_SELFTEST=1, the plumbing self-test).
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402

# The blobs of src/new_file_intro.c that are pointer tables: (macro, ROM start, ROM end)
BLOBS = [
    ("CA_TABLES_79C5C0_79CDD8", 0x79C5C0, 0x79CDD8),  # message and location, 7 languages
    ("CA_TABLES_79CE10_79E6A0", 0x79CE10, 0x79E6A0),  # navigation, 7 languages
]
MONOLOGUE = ("CA_MONOLOGUE_TABLE", 0x79E6EC, 0x79E738)  # sMonologueTextPointersEnglish


def symbol(idx):
    return f"sCaText_{idx}"


def slot_pointers():
    """{ROM offset of a pointer of the English slot: ID}."""
    out = {}
    for category in catext.CATEGORIES:
        for idx, off in zip(catext.entry_ids(category), catext.pointer_offsets(category, catext.SLOT)):
            out[off] = idx
    return out


def slot_text(selftest):
    """[(ID, [u16 codes], source)] for every entry of the English slot."""
    out = []
    for category in catext.CATEGORIES:
        catalan, path = ({}, None) if selftest else catext.read_translation(category)
        vanilla = catext.vanilla_codes(category, catext.SLOT)
        unknown = set(catalan) - {idx for idx, _, _ in vanilla}
        if unknown:
            sys.exit(f"error: {path}: unknown IDs: {', '.join(sorted(unknown))}")
        for idx, _, codes in vanilla:
            if idx in catalan:
                try:
                    out.append((idx, catext.encode(catalan[idx][0]), "ca"))
                except KeyError as e:
                    sys.exit(f"error: {path}:{catalan[idx][1]}: {idx}: {e}")
            else:
                out.append((idx, codes, "en"))
    return out


def gen_asm(selftest):
    lines = ["@ Generated by translation/ca/tools/gentext.py. Do not edit.",
             "@ The text of the English slot, appended after everything else in the ROM.",
             "\t.section .rodata", "\t.align 2", ""]
    for idx, codes, source in slot_text(selftest):
        vals = codes + [catext.CHAR_TERMINATOR]
        lines += [f"\t.global {symbol(idx)}", f"{symbol(idx)}: @ {source}"]
        lines += ["\t.2byte " + ",".join(f"0x{v:04X}" for v in vals[i:i + 16])
                  for i in range(0, len(vals), 16)]
    return "\n".join(lines) + "\n"


def table_macro(name, start, end, slot):
    words = []
    for off in range(start, end, 4):
        if off in slot:
            words.append(symbol(slot.pop(off)))
        else:
            words.append(f"(const u16*)0x{catext.u32(off):08x}")
    return f"#define {name} \\\n" + ", \\\n".join("    " + w for w in words) + "\n"


def gen_tables():
    slot = slot_pointers()
    out = ["// Generated by translation/ca/tools/gentext.py. Do not edit.",
           "// The pointer tables of src/new_file_intro.c that hold English text pointers: every",
           "// pointer as in the ROM, except the English ones, which point at the appended text.",
           "#ifndef CA_TEXT_TABLES_H", "#define CA_TEXT_TABLES_H", ""]
    out += [f"extern const u16 {symbol(idx)}[];" for idx in slot.values()]
    out.append("")
    for name, start, end in BLOBS + [MONOLOGUE]:
        out.append(table_macro(name, start, end, slot))
    if slot:
        sys.exit(f"error: {len(slot)} English pointers are outside the known tables")
    out.append("#endif // CA_TEXT_TABLES_H")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["asm", "tables"])
    ap.add_argument("output")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    out = Path(a.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(gen_asm(a.selftest) if a.what == "asm" else gen_tables(), encoding="utf-8")
