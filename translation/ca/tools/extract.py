#!/usr/bin/env python3
"""Dumps the text of every language of the base ROM into translation/ca/text/<language>/.

  extract.py            write text/<language>/<category>.txt for the seven languages
  extract.py --check    re-encode every dump and compare it with the ROM (exit 1 on a difference)

One entry per line, `ID = "text"`, in the syntax of translation/ca/charmap.txt. IDs are the
table and the index in it (MESSAGE_07 is entry 7 of sMessageTextPointers[language]), so every
language has the same IDs. The navigation table is split where the game splits it: NAV_000 to
NAV_113 are sNavConversationTextPointers, PAUSE_000 on are sPauseScreenTextPointers (the same
table from entry 114). The Catalan text lives one level up, in text/<category>.txt.

--check also proves the dumps account for the whole text blob: every string of every table,
re-encoded, is byte for byte what its pointer reads in the ROM, and together the strings cover
the blob (0x6b2fac-0x72eee0) without a gap other than alignment padding.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402


def dump(category, language):
    lines = [f"# {catext.HEADERS[category]}: vanilla {language} text of the US ROM.",
             "# Generated by translation/ca/tools/extract.py. Do not edit: the Catalan text is in",
             f"# translation/ca/text/{catext.CATEGORIES[category][0]}.", ""]
    for idx, _, codes in catext.vanilla_codes(category, language):
        lines.append(f'{idx} = "{catext.decode(codes)}"')
    return "\n".join(lines) + "\n"


def cmd_extract(base):
    for language in catext.LANGUAGES:
        for category in catext.CATEGORIES:
            path = catext.dump_path(category, language, base)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(dump(category, language), encoding="utf-8")
    print(f"wrote {len(catext.LANGUAGES) * len(catext.CATEGORIES)} files under {base}")


def check(base):
    """Returns a list of problems (empty when the dumps reproduce the ROM)."""
    problems, covered, total = [], [], 0
    rom = catext.rom()
    for language in catext.LANGUAGES:
        for category in catext.CATEGORIES:
            path = catext.dump_path(category, language, base)
            try:
                entries = catext.read_entries(path)
            except ValueError as e:
                problems.append(str(e))
                continue
            vanilla = catext.vanilla_codes(category, language)
            if list(entries) != [idx for idx, _, _ in vanilla]:
                problems.append(f"{path}: IDs differ from the ROM table (run extract.py)")
                continue
            for idx, off, codes in vanilla:
                total += 1
                try:
                    data = catext.to_bytes(catext.encode(entries[idx][0]))
                except KeyError as e:
                    problems.append(f"{path}:{entries[idx][1]}: {idx}: {e}")
                    continue
                if data != rom[off:off + len(data)] or data != catext.to_bytes(codes):
                    problems.append(f"{path}:{entries[idx][1]}: {idx}: differs from the ROM at 0x{off:x}")
                covered.append((off, off + len(data)))
    # Coverage of the blob: strings in address order. The only bytes no table points at are
    # alignment padding and six lone terminators (an unreferenced empty string after the last
    # navigation string of every language but the first).
    start, end = catext.TEXT_BLOB
    terminator = catext.to_bytes([])

    def unowned(a, b):
        gap = rom[a:b]
        return gap not in (b"", terminator) and (len(gap) > 3 or any(gap))

    pos = start
    for a, b in sorted(set(covered)):
        if a < start or b > end:
            problems.append(f"string at 0x{a:x} is outside the text blob")
        elif a > pos and unowned(pos, a):
            problems.append(f"blob bytes 0x{pos:x}-0x{a:x} belong to no table")
        pos = max(pos, b)
    if unowned(pos, end):
        problems.append(f"blob bytes 0x{pos:x}-0x{end:x} belong to no table")
    return problems, total


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify the dumps against the ROM")
    ap.add_argument("--text-dir", type=Path, default=catext.CA / "text")
    a = ap.parse_args()
    if not a.check:
        cmd_extract(a.text_dir)
        sys.exit(0)
    problems, total = check(a.text_dir)
    for p in problems[:50]:
        print(p)
    print(f"{total} strings checked, {len(problems)} problems")
    sys.exit(1 if problems else 0)
