#!/usr/bin/env python3
"""Edited graphics for LANG_CA=1.

  gfx.py asm OUTPUT.s [--selftest]   every asset of gfx_assets.json as LZ77 data for the object
                                     appended after everything else in the ROM. Each one is the
                                     PNG in translation/ca/gfx/<asset>.png, or the vanilla
                                     graphic where there is no PNG (and always with --selftest)
  gfx.py export ASSET OUT.png        the vanilla graphic as an indexed PNG to edit
  gfx.py check                       every PNG has the size and the palette indices its asset
                                     needs, and decompresses back to itself
  gfx.py roundtrip                   the codec reproduces every asset: PNG -> tiles -> LZ77 ->
                                     tiles gives the vanilla tiles

gfx_assets.json: "<asset>": {"source": the vanilla asset in database.json, "symbol": the label
the C code points at under LANG_CA, "tiles": the number of 4bpp tiles (the VRAM space it is
decompressed into: a PNG may not be bigger), "pointers": ROM offsets of the pointers that are
repointed (romcheck.py allows exactly those)}. An asset with "raw": true is not tiles but
data of a fixed size (a tilemap): its file is translation/ca/gfx/<asset>.tm, written by the
tool that composes the graphic, and it must be exactly as long as the vanilla data.

A PNG is indexed (palette indices 0-15 are the tile's pixels; the palette itself is only for
viewing) and 256 px wide: 32 tiles per row, in tile order.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402
import lz77  # noqa: E402

GFX = catext.CA / "gfx"
ASSETS = Path(__file__).resolve().parent / "gfx_assets.json"
COLS = 32
GREY = [c for i in range(16) for c in ((0, 0, 48) if i == 0 else (40 + 14 * i,) * 3)]


def assets():
    return json.loads(ASSETS.read_text())


def database():
    return {e["path"]: e for e in json.loads((catext.ROOT / "database.json").read_text())}


def vanilla_tiles(info, db=None):
    e = (db or database())[info["source"]]
    return lz77.decompress(catext.rom(), int(e["addr"]["us"], 16))[0]


def tiles_to_rows(raw):
    n = len(raw) // 32
    rows = [[0] * (COLS * 8) for _ in range((n + COLS - 1) // COLS * 8)]
    for t in range(n):
        for y in range(8):
            for xb in range(4):
                b = raw[t * 32 + y * 4 + xb]
                rows[(t // COLS) * 8 + y][(t % COLS) * 8 + xb * 2] = b & 15
                rows[(t // COLS) * 8 + y][(t % COLS) * 8 + xb * 2 + 1] = b >> 4
    return rows


def rows_to_tiles(rows):
    out = bytearray()
    for ty in range(len(rows) // 8):
        for tx in range(COLS):
            for y in range(8):
                r = rows[ty * 8 + y]
                for xb in range(4):
                    out.append(r[tx * 8 + xb * 2] | (r[tx * 8 + xb * 2 + 1] << 4))
    return bytes(out)


def read_png(path, info):
    from PIL import Image
    img = Image.open(path)
    if img.mode != "P":
        sys.exit(f"error: {path} must be an indexed PNG")
    if img.width != COLS * 8 or img.height % 8 or img.width * img.height // 64 > info["tiles"]:
        sys.exit(f"error: {path} is {img.size}; it must be {COLS * 8} px wide and hold at most {info['tiles']} tiles")
    rows = [[img.getpixel((x, y)) for x in range(img.width)] for y in range(img.height)]
    if any(v > 15 for r in rows for v in r):
        sys.exit(f"error: {path} uses palette indices over 15")
    return rows


def asset_tiles(name, info, selftest=False, db=None):
    """The uncompressed data of an asset as built: tiles, or the raw bytes of a "raw" asset."""
    if info.get("raw"):
        path = GFX / f"{name}.tm"
        vanilla = vanilla_tiles(info, db)
        if selftest or not path.exists():
            return vanilla
        data = path.read_bytes()
        if len(data) != len(vanilla):
            sys.exit(f"error: {path} is {len(data)} bytes, the vanilla data is {len(vanilla)}")
        return data
    png = GFX / f"{name}.png"
    if selftest or not png.exists():
        return vanilla_tiles(info, db)
    return rows_to_tiles(read_png(png, info))


def cmd_asm(out, selftest):
    db = database()
    lines = ["@ Generated by translation/ca/tools/gfx.py. Do not edit.",
             "@ The edited graphics, appended after everything else in the ROM.",
             "\t.section .rodata", ""]
    for name, info in assets().items():
        data = lz77.compress(asset_tiles(name, info, selftest, db))
        lines += ["\t.align 2", f"\t.global {info['symbol']}", f"{info['symbol']}: @ {name}"]
        lines += ["\t.byte " + ",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines) + "\n")


def cmd_export(name, out):
    from PIL import Image
    rows = tiles_to_rows(vanilla_tiles(assets()[name]))
    img = Image.new("P", (COLS * 8, len(rows)))
    img.putpalette(GREY + [0] * (768 - 48))
    for y, r in enumerate(rows):
        for x, v in enumerate(r):
            img.putpixel((x, y), v)
    img.save(out)


def cmd_check():
    n = 0
    for name, info in assets().items():
        png = GFX / (f"{name}.tm" if info.get("raw") else f"{name}.png")
        if not png.exists():
            print(f"{name}: no file (the vanilla graphic is used)")
            continue
        tiles = asset_tiles(name, info)
        if lz77.decompress(lz77.compress(tiles))[0] != tiles:
            sys.exit(f"error: {name}: the compressed data doesn't decompress to the PNG")
        n += 1
    print(f"{n} edited graphics ok")


def cmd_roundtrip():
    db = database()
    for name, info in assets().items():
        raw = vanilla_tiles(info, db)
        if not info.get("raw") and len(raw) != info["tiles"] * 32:
            sys.exit(f"error: {name}: {len(raw) // 32} tiles in the ROM, gfx_assets.json says {info['tiles']}")
        tiles_ok = info.get("raw") or rows_to_tiles(tiles_to_rows(raw)) == raw
        if not tiles_ok or lz77.decompress(lz77.compress(raw))[0] != raw:
            sys.exit(f"error: {name}: the round trip changes the graphic")
    print(f"{len(assets())} assets round-trip")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("asm")
    a.add_argument("output")
    a.add_argument("--selftest", action="store_true")
    e = sub.add_parser("export")
    e.add_argument("asset")
    e.add_argument("png")
    sub.add_parser("check")
    sub.add_parser("roundtrip")
    args = ap.parse_args()
    if args.cmd == "asm":
        cmd_asm(args.output, args.selftest)
    elif args.cmd == "export":
        cmd_export(args.asset, args.png)
    elif args.cmd == "check":
        cmd_check()
    else:
        cmd_roundtrip()
