#!/usr/bin/env python3
"""Font patch for LANG_CA=1: glyph overlay on the extracted font, and width overrides.

  font.py widths OUTPUT        sCharacterWidths initializer with font/widths.txt applied
  font.py build OUTPUT         data/text_characters.gfx with every font/glyphs/XXXX.png on top,
                               written as an include (the format preproc gives INCBIN_U8)
  font.py export ID PNG        the vanilla glyph ID (hex) as an editable indexed PNG
  font.py check                font/glyphs/*.png are valid (size, palette indices)
  --vanilla (widths, build)    ignore the Catalan overrides (CA_SELFTEST)

Glyph layout (TextDrawCharacter, src/text.c): glyph `id` is two stacked 4bpp tiles, top at
id*32 and bottom at id*32 + 0x400; glyphs wider than 8 px also use id+1. A glyph PNG is 8x16
(or 16x16) and indexed with Fusion's font indices: 0 = background, 2 = fill, 3 = outline
(1 is unused by the letters). {COLOR(n)} adds 2n to the fill and the outline, so nothing else
may be used. Keep each glyph's outline inside its width, like the vanilla font: the font is
edited in place, so its size never changes.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402

from PIL import Image  # noqa: E402

FONT = catext.ROOT / "data" / "text_characters.gfx"
GLYPHS = catext.CA / "font" / "glyphs"
FONT_SIZE = 0x30000  # 192 KB: sCharactersGfx[192 * 1024]

# Editing palette: background, unused, fill, outline.
PALETTE = [(16, 32, 56), (255, 0, 255), (255, 255, 255), (8, 8, 24)]
ALLOWED = {0, 2, 3}


def glyph_tiles(cid, wide):
    """Byte offsets of a glyph's tiles in PNG tile order (row-major, 1 or 2 tiles wide)."""
    cols = 2 if wide else 1
    return [(cid + c) * 32 + r * 0x400 for r in (0, 1) for c in range(cols)]


def glyph_pixels(font, cid):
    """16 rows x 16 columns of 4-bit values (two tiles wide)."""
    px = [[0] * 16 for _ in range(16)]
    for half in (0, 1):
        for t in (0, 1):
            off = (cid + t) * 32 + half * 0x400
            for y in range(8):
                for xb in range(4):
                    b = font[off + y * 4 + xb]
                    px[half * 8 + y][t * 8 + xb * 2] = b & 0xF
                    px[half * 8 + y][t * 8 + xb * 2 + 1] = b >> 4
    return px


def read_glyph(png):
    """[[index]] rows of a glyph PNG; exits on a wrong size or palette index."""
    img = Image.open(png)
    if img.mode != "P" or img.size not in ((8, 16), (16, 16)):
        sys.exit(f"error: {png} must be an indexed PNG of 8x16 or 16x16 px, is {img.mode} {img.size}")
    rows = [[img.getpixel((x, y)) for x in range(img.width)] for y in range(16)]
    bad = {v for r in rows for v in r} - ALLOWED
    if bad:
        sys.exit(f"error: {png} uses palette indices {sorted(bad)}; only 0 (background), 2 (fill), 3 (outline)")
    return rows


def overlay(font, cid, rows):
    for t in range(len(rows[0]) // 8):
        for half in (0, 1):
            off = (cid + t) * 32 + half * 0x400
            for y in range(8):
                for xb in range(4):
                    lo, hi = rows[half * 8 + y][t * 8 + xb * 2], rows[half * 8 + y][t * 8 + xb * 2 + 1]
                    font[off + y * 4 + xb] = lo | (hi << 4)


def load(vanilla=False):
    """The font as bytes, with the Catalan glyphs unless `vanilla`."""
    font = bytearray(FONT.read_bytes())
    if len(font) != FONT_SIZE:
        sys.exit(f"error: {FONT} is {len(font)} bytes, expected {FONT_SIZE}")
    if not vanilla:
        w = catext.widths(catalan=True)
        for png in sorted(GLYPHS.glob("*.png")):
            cid = int(png.stem, 16)
            rows = read_glyph(png)
            wide = cid >= len(w) or w[cid] > 8
            if len(rows[0]) != (16 if wide else 8):
                sys.exit(f"error: {png} must be {16 if wide else 8}x16 px (width {w[cid]})")
            overlay(font, cid, rows)
    return bytes(font)


def cmd_widths(out, vanilla=False):
    w = catext.widths(catalan=not vanilla)
    rows = [", ".join(str(v) for v in w[i:i + 16]) for i in range(0, len(w), 16)]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("// Generated by translation/ca/tools/font.py from font/widths.txt. Do not edit.\n    "
                         + ",\n    ".join(rows) + "\n")


def cmd_build(out, vanilla=False):
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("{" + ",".join(str(b) for b in load(vanilla)) + "}\n")


def cmd_export(cid_hex, png):
    cid = int(cid_hex, 16)
    w = catext.widths(catalan=False)
    wide = cid >= len(w) or w[cid] > 8
    px = glyph_pixels(FONT.read_bytes(), cid)
    img = Image.new("P", (16 if wide else 8, 16))
    img.putpalette([c for rgb in PALETTE for c in rgb] + [0] * (768 - 12))
    for y in range(16):
        for x in range(img.width):
            img.putpixel((x, y), px[y][x])
    img.save(png)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("widths", "build"):
        s = sub.add_parser(name)
        s.add_argument("output")
        s.add_argument("--vanilla", action="store_true", help="ignore the Catalan overrides")
    e = sub.add_parser("export")
    e.add_argument("id")
    e.add_argument("png")
    sub.add_parser("check")
    a = ap.parse_args()
    if a.cmd == "widths":
        cmd_widths(a.output, a.vanilla)
    elif a.cmd == "build":
        cmd_build(a.output, a.vanilla)
    elif a.cmd == "check":
        load()
        print(f"{len(list(GLYPHS.glob('*.png')))} glyph overrides ok")
    else:
        cmd_export(a.id, a.png)
